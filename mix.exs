defmodule MishkaDocument.MixProject do
  use Mix.Project

  def project do
    [
      app: :mishka_document,
      version: "0.0.1",
      elixir: "~> 1.18",
      start_permanent: Mix.env() == :prod,
      deps: deps(),
      consolidate_protocols: Mix.env() != :dev,
      aliases: aliases(),
      elixirc_paths: elixirc_paths(Mix.env()),
      package: package()
    ]
  end

  # `priv/cms_ui_kits` AND NOTHING ELSE UNDER `priv`. The bundle is the extension's live components —
  # `MishkaDocument.Kit.bundle_path/0` reads it out of `:code.priv_dir/1`, so leaving it behind would
  # point a hex install at a file that does not exist and give that site no document components at
  # all. The rest of `priv` is generated by `mix ash.codegen` for the standalone test database,
  # including tables this extension does not own, so publishing it would ship someone else's schema.
  # `config` and `test` are absent for the same reason — they exist only to run the suite on its own.
  defp package do
    [
      licenses: ["Apache-2.0"],
      files: ~w(lib priv/cms_ui_kits .formatter.exs mix.exs LICENSE README*)
    ]
  end

  # Run "mix help compile.app" to learn about applications.
  def application do
    [
      extra_applications: [:logger],
      mod: {MishkaDocument.Application, []}
    ]
  end

  # Run "mix help deps" to learn about dependencies.
  defp deps do
    [
      {:decimal, "~> 3.2", override: true},
      {:sourceror, "~> 1.12", only: [:dev, :test]},
      {:lazy_html, "~> 0.1", only: :test},
      {:open_api_spex, "~> 3.22"},
      {:ash_paper_trail, "~> 0.7"},
      {:ash_archival, "~> 2.0"},
      {:ash_postgres, "~> 2.13"},
      {:ash_json_api, "~> 1.7"},
      {:ash_phoenix, "~> 2.3"},
      {:ash, "~> 3.33"},
      {:ash_slug, "~> 0.2"},
      {:html_sanitize_ex, "~> 1.5"},
      {:makeup, "~> 1.2"},
      {:makeup_elixir, "~> 1.0"},
      {:makeup_eex, "~> 2.0"},
      {:makeup_erlang, "~> 1.1"},
      {:makeup_html, "~> 1.0"},
      {:makeup_json, "~> 1.0"},
      {:makeup_diff, "~> 0.1"},
      {:makeup_sql, "~> 0.1"},
      {:makeup_ts, "~> 0.2"},
      {:makeup_css, "~> 0.2"},
      {:ash_events, "~> 0.8"},
      {:guarded_struct, "~> 0.1"},
      {:mishka_installer, "~> 0.1"},
      {:igniter, "~> 0.8", only: [:dev, :test]},
      {:mishka_cms_core, path: "../mishka_cms_core"},
      {:mishka_gervaz, path: "../mishka_gervaz"}
    ]
  end

  defp aliases() do
    [test: ["ash.setup --quiet", "test"], setup: "ash.setup"]
  end

  defp elixirc_paths(:test),
    do: elixirc_paths(:dev) ++ ["test/support"]

  defp elixirc_paths(_),
    do: ["lib"]
end
